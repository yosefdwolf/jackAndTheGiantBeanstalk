"""Write out every prompt a story sends to the image model, to read before paying for any pictures. Free.

    python -m scripts.show_prompts little_red_riding_hood          # writes docs/prompts/little_red_riding_hood.md
    python -m scripts.show_prompts little_red_riding_hood girl     # as a girl's book

The story text uses the reader's own name; the prompts use the story's hero name (as real books do).
"""
import sys
from pathlib import Path

from app.book.prompts import PromptBuilder
from app.book.story import HERO, ROOT, Casting, story_for
from app.book.styles import get_style


def main(story_key: str, gender: str = "boy") -> Path:
    story = story_for(story_key)
    if story.key != story_key:
        raise SystemExit(f"No story file stories/{story_key}.yaml")
    prompts = PromptBuilder(get_style(story.style), story, Casting(story, gender))
    reader = Casting(story, gender, "Sam")  # the story text, as a reader called Sam would see it
    out = [f"# {story.title}: every prompt ({gender}'s book)", "",
           "Generated by `scripts/show_prompts.py` from the story file. The page text uses a reader called Sam.", ""]
    out += ["## The child's cartoon (drawn from their photo)", "", "```", prompts.hero_sheet(), "```", ""]
    for character in story.characters.values():
        out += [f"## Character sheet: {reader.fill(character.name)} (drawn once)", "", "```",
                prompts.character_sheet(character), "```", ""]
    for spec in story.pages:
        if spec.type != "illustrated":
            out += [f"## Page {spec.number}: {spec.type.replace('_', ' ')} (no picture)", ""]
            continue
        out += [f"## Page {spec.number}", "", f"**Words on the page** (text at the {spec.text_zone}): "
                f"{reader.fill(spec.text)}", "", f"**While it's drawn:** {spec.progress}", ""]
        if HERO in spec.cast:  # the scene, drawn once per story, then the child added in every book
            others = [k for k in spec.cast if k != HERO] + [f"scene-{n}" for n in spec.see]
            out += [f"**The scene** (drawn once for every book; pictures sent: {', '.join(others) or 'none'}):", "",
                    "```", prompts.scene(spec, tuple(spec.see)), "```", "",
                    "**Each book's page** (pictures sent: hero, the scene):", "", "```", prompts.on_scene(spec), "```", ""]
        else:
            out += [f"**The whole page, shared by every book** (pictures sent: "
                    f"{', '.join(spec.cast)}):", "", "```", prompts.page(spec), "```", ""]
    path = ROOT / "docs" / "prompts" / f"{story.key}.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(out))
    return path


if __name__ == "__main__":
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    print(main(*sys.argv[1:3]))
